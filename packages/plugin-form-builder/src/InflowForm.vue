<script setup lang="ts">
import { computed, inject, markRaw, provide, toRaw, watch } from 'vue'
import { JsonForms } from '@jsonforms/vue'
import type { JsonSchema, UISchemaElement } from '@jsonforms/core'
import type { InflowActionRegistry } from './InflowActionRegistry'
import { InflowActionRegistryKey } from './InflowActionRegistry'
import type { InflowFormEnvelope, InflowHostContext, InflowPluginCall } from './types'
import { withBuiltinActions } from './actions'
import {
  InflowFormControllerKey,
  InflowHostContextKey,
  createInflowFormController,
} from './InflowFormController'
import { inflowControlTester, inflowLayoutTester } from './inflowTester'
import InflowControlRenderer from './InflowControlRenderer.vue'
import InflowLayoutRenderer from './InflowLayoutRenderer.vue'

/**
 * A plugin's form, rendered.
 *
 * The whole `x-inflow-ui` contract in one component: register it, hand it the
 * schema and UI schema a plugin served and a way to reach that plugin, and every
 * documented use case works — buttons that call the plugin's meta functions,
 * answers patched into fields, and answers that carry a *new* form re-rendering
 * the dialog in place.
 *
 * It exists because the interesting part cannot be done from inside a renderer.
 * `<JsonForms>` seeds its core from its props and re-seeds it whenever `data`
 * changes; in a host that two-way binds data — all of them — a schema pushed
 * into the core is reverted by the next keystroke. Owning `schema` / `uischema`
 * / `data` out here is what makes "the plugin sent back a new form" stick, so
 * this component owns them and `<JsonForms>` becomes an implementation detail.
 *
 * A host that needs its own `<JsonForms>` can still use the renderers directly;
 * everything works except that a replaced schema lasts only until the host
 * re-seeds its props.
 */
const props = withDefaults(
  defineProps<{
    /** The JSON Schema to render. */
    schema?: JsonSchema
    /** The UI Schema to render. Generated by JSON Forms when omitted. */
    uischema?: UISchemaElement
    /** The form's data. Supports `v-model:data`. */
    data?: any
    /**
     * The host's own renderer set — vanilla, Vuetify, your own. The Inflow
     * renderers are prepended; they only ever match elements carrying
     * `x-inflow-ui`, so everything else falls through to yours untouched.
     */
    renderers?: any[]
    cells?: any[]
    config?: any
    readonly?: boolean
    /** The inflowv1 plugin this form came from. Without it, plugin calls report rather than fail silently. */
    pluginId?: string
    /** The settings profile sent with every plugin call (credentials, endpoint). */
    settings?: Record<string, unknown>
    /** How to reach this plugin's meta functions. Falls back to the app-wide `call`. */
    call?: InflowPluginCall
    /** Actions for this form, merged over the app-wide registry and the built-ins. */
    actions?: InflowActionRegistry
    /** Render the built-in status / error line under the form. */
    showStatus?: boolean
  }>(),
  { showStatus: true },
)

const emit = defineEmits<{
  (e: 'update:data', value: any): void
  (e: 'change', event: { data: any; errors: any }): void
  /**
   * The rendered document changed — most usefully when an action's answer
   * carried a new form, so a host can persist what the user is now looking at.
   */
  (e: 'update:form', envelope: { schema?: JsonSchema; uischema?: UISchemaElement }): void
}>()

// ---- Live document ----------------------------------------------------------

const controller = createInflowFormController({
  schema: props.schema,
  uischema: props.uischema,
  data: props.data,
})

// The props stay authoritative: when the host swaps the form (a different action
// selected, a settings dialog reopened) that wins over whatever a button had
// replaced it with. Between those moments the controller is authoritative, which
// is the half `<JsonForms>` alone cannot do.
watch(() => props.schema, (v) => { controller.schema.value = v })
watch(() => props.uischema, (v) => { controller.uischema.value = v })
watch(
  () => props.data,
  (v) => {
    if (JSON.stringify(v) !== JSON.stringify(controller.data.value)) controller.data.value = v
  },
)

watch([controller.schema, controller.uischema], ([schema, uischema]) => {
  emit('update:form', { schema, uischema })
})

provide(InflowFormControllerKey, controller)

// ---- Host context -----------------------------------------------------------

const appHost = inject(InflowHostContextKey, undefined)

// Per-form values override the app-wide ones, and only where given: an app
// configures `call` once in main.ts, each form supplies the plugin and profile
// it is bound to.
watch(
  () => [appHost?.value, props.pluginId, props.settings, props.call] as const,
  () => {
    const next: InflowHostContext = { ...(appHost?.value ?? {}) }
    if (props.pluginId !== undefined) next.pluginId = props.pluginId
    if (props.settings !== undefined) next.settings = props.settings
    if (props.call !== undefined) next.call = props.call
    controller.host.value = next
  },
  { immediate: true, deep: true },
)

// ---- Actions ----------------------------------------------------------------

const appActions = inject(InflowActionRegistryKey, {} as InflowActionRegistry)

/**
 * Built-ins first, then the app's registry, then this form's — each layer
 * overriding the last by name. The default behaviour is a floor a host can
 * replace, not a lock.
 */
const actions = computed<InflowActionRegistry>(() =>
  withBuiltinActions({ ...appActions, ...(props.actions ?? {}) }),
)

// Provided as a proxy over the computed rather than as its current value:
// `provide` only runs during setup, and the registry's public type is a plain
// record (hosts provide one by hand), so a ref cannot be handed over without
// breaking them. Forwarding reads keeps a late-changing `actions` prop live.
provide(
  InflowActionRegistryKey,
  new Proxy({} as InflowActionRegistry, {
    get: (_, name: string) => actions.value[name],
    has: (_, name: string) => name in actions.value,
    ownKeys: () => Reflect.ownKeys(actions.value),
    getOwnPropertyDescriptor: (_, name: string) => ({
      value: actions.value[name],
      enumerable: true,
      configurable: true,
    }),
  }),
)

// ---- Renderers --------------------------------------------------------------

/**
 * markRaw every renderer. JSON Forms keeps the array in a reactive context,
 * which would otherwise proxy each component and destabilise its identity — the
 * visible symptom being controls that stop reflecting their value (an enum
 * `<select>` rendering blank). Per-component because InflowControlRenderer
 * rebuilds a filtered copy of the array for its inner DispatchRenderer.
 *
 * `toRaw` first, because a host is free to keep its renderer set in reactive
 * state: reading a component *through* a proxy hands us the proxy, and marking
 * that marks the wrong object — the vnode still gets the proxy and Vue warns.
 * Unwrapping first is what makes markRaw land on the component itself.
 */
const renderers = computed(() => {
  const host = toRaw(props.renderers ?? []).filter(
    (r) => r.tester !== inflowControlTester && r.tester !== inflowLayoutTester,
  )
  return markRaw([
    { tester: inflowControlTester, renderer: markRaw(InflowControlRenderer) },
    { tester: inflowLayoutTester, renderer: markRaw(InflowLayoutRenderer) },
    ...host.map((r) => {
      const entry = toRaw(r)
      return { tester: entry.tester, renderer: markRaw(toRaw(entry.renderer)) }
    }),
  ])
})

// ---- Data flow --------------------------------------------------------------

/**
 * JSON Forms fires `change` once on mount as well as on every edit. The mount
 * one carries the data we just handed it, so it is filtered out — otherwise
 * merely opening a form would write to the host and mark its document dirty.
 */
function onChange(event: { data: any; errors: any }) {
  emit('change', event)
  if (JSON.stringify(event.data) === JSON.stringify(controller.data.value)) return
  controller.data.value = event.data
  emit('update:data', event.data)
}

defineExpose({
  /** Replace the rendered form from outside — the same path an action's answer takes. */
  setForm: (envelope: InflowFormEnvelope) => controller.setForm(envelope),
  controller,
})
</script>

<template>
  <div class="inflow-form">
    <JsonForms
      :data="controller.data.value"
      :schema="(controller.schema.value as any)"
      :uischema="(controller.uischema.value as any)"
      :renderers="renderers"
      :cells="cells"
      :config="config"
      :readonly="readonly"
      @change="onChange"
    />

    <!--
      The only channel an action has to say anything: the contract returns void,
      and a meta function that answers `{"error": …}` is patching a field called
      `error` into the form, not raising one. Slot it to render in your own
      design system; the default is unstyled by design.
    -->
    <slot
      name="status"
      :busy="controller.busy.value"
      :status="controller.status.value"
      :error="controller.error.value"
    >
      <p v-if="showStatus && controller.busy.value" class="inflow-form-busy">Working…</p>
      <p v-else-if="showStatus && controller.error.value" class="inflow-form-error">
        {{ controller.error.value }}
      </p>
      <p v-else-if="showStatus && controller.status.value" class="inflow-form-status">
        {{ controller.status.value }}
      </p>
    </slot>
  </div>
</template>
